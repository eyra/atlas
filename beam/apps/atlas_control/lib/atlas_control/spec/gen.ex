defmodule AtlasControl.Spec.Gen do
  @moduledoc """
  The generators: from `AtlasControl.Spec.Blocks.__spec__/0` to

  - `beam/apps/atlas_control/lib/atlas_control/blocks.ex`: server code, one builder per
    block and model that checks a block before Control sends it;
  - `clients/tui/lib/atlas_tui/blocks.ex`: client code, one struct per block and model
    and a decoder that turns an unknown or broken block into a fallback;
  - `spec/control/blocks.json`: the catalogue as data, for clients in other languages.

  Run `mix atlas.gen`; `mix atlas.gen --check` fails when a file is out of date.
  """

  @root Path.expand("../../../../../..", __DIR__)

  def root, do: @root

  @doc "`[{path relative to the repository root, content}]`."
  def files(spec \\ AtlasControl.Spec.Blocks.__spec__()) do
    [
      {"beam/apps/atlas_control/lib/atlas_control/blocks.ex", server(spec)},
      {"clients/tui/lib/atlas_tui/blocks.ex", client(spec)},
      {"spec/control/blocks.json", json(spec)}
    ]
  end

  @header "# Generated by `mix atlas.gen` from AtlasControl.Spec.Blocks. Do not edit."

  # Server

  defp server(spec) do
    builders =
      for entry <- spec.models ++ spec.blocks do
        kind = if entry in spec.blocks, do: "block", else: "model"

        """
        @doc "Build a `#{entry.name}` #{kind}. Fields: #{field_list(entry)}."
        def #{entry.name}(props), do: build(#{inspect(kind)}, #{inspect(Atom.to_string(entry.name))}, props)
        """
      end

    """
    #{@header}
    defmodule AtlasControl.Blocks do
      @moduledoc \"\"\"
      Builders for the blocks Control sends (spec #{spec.version}). A block is
      `%{"type" => name, "props" => props}`; a model is a plain map. An optional prop
      without a value is left out. A wrong or missing prop raises: that is a bug in
      Control, never something a client should see.
      \"\"\"

      @fields #{inspect(fields_table(spec), limit: :infinity)}

      def version, do: #{inspect(spec.version)}

    #{Enum.join(builders, "\n")}

      defp build(kind, name, props) do
        fields = Map.fetch!(@fields, name)
        props = Map.new(props, fn {k, v} -> {to_string(k), v} end)

        case Map.keys(props) -- Enum.map(fields, &elem(&1, 0)) do
          [] -> :ok
          unknown -> raise ArgumentError, "\#{name} has no field(s) \#{inspect(unknown)}"
        end

        checked =
          for {field, type, required} <- fields, reduce: %{} do
            acc ->
              case Map.get(props, field) do
                nil when required -> raise ArgumentError, "\#{name}.\#{field} is required"
                nil -> acc
                value -> Map.put(acc, field, check!(type, value, "\#{name}.\#{field}"))
              end
          end

        if kind == "block", do: %{"type" => name, "props" => checked}, else: checked
      end

      defp check!("string", value, _at) when is_binary(value), do: value
      defp check!("integer", value, _at) when is_integer(value), do: value
      defp check!("boolean", value, _at) when is_boolean(value), do: value
      defp check!({:list, type}, values, at) when is_list(values), do: Enum.map(values, &check!(type, &1, at))

      defp check!(model, value, _at) when is_map_key(@fields, model) and (is_map(value) or is_list(value)),
        do: build("model", model, value)

      defp check!(type, value, at), do: raise(ArgumentError, "\#{at} must be \#{inspect(type)}, got: \#{inspect(value)}")
    end
    """
    |> format()
  end

  defp fields_table(spec) do
    Map.new(spec.models ++ spec.blocks, fn entry ->
      {Atom.to_string(entry.name),
       Enum.map(entry.fields, &{Atom.to_string(&1.name), type_name(&1.type), &1.required})}
    end)
  end

  defp type_name({:list, inner}), do: {:list, type_name(inner)}
  defp type_name(type), do: Atom.to_string(type)

  defp field_list(entry) do
    Enum.map_join(entry.fields, ", ", fn f ->
      "`#{f.name}`#{if f.required, do: " (required)", else: ""}"
    end)
  end

  # Client

  defp client(spec) do
    structs =
      for entry <- spec.models ++ spec.blocks do
        """
        defmodule #{Macro.camelize(Atom.to_string(entry.name))} do
          @moduledoc false
          defstruct #{inspect(Enum.map(entry.fields, & &1.name))}
        end
        """
      end

    """
    #{@header}
    defmodule AtlasTui.Blocks do
      @moduledoc \"\"\"
      The blocks Control sends (spec #{spec.version}), decoded into structs. An unknown
      block, or one that fails to decode, becomes an `AtlasTui.Blocks.Fallback`, and
      the rest of the page still renders. Unknown keys are ignored.
      \"\"\"

      @fields #{inspect(client_table(spec), limit: :infinity)}
      @blocks #{inspect(Enum.map(spec.blocks, &Atom.to_string(&1.name)))}

      def version, do: #{inspect(spec.version)}

      defmodule Fallback do
        @moduledoc false
        defstruct [:type, :reason]
      end

    #{Enum.join(structs, "\n")}

      @doc "Decode one block from its JSON map."
      def decode(%{"type" => type} = block) when type in @blocks do
        case decode_model(type, Map.get(block, "props") || %{}) do
          {:ok, struct} -> struct
          {:error, reason} -> %Fallback{type: type, reason: reason}
        end
      end

      def decode(%{"type" => type}), do: %Fallback{type: type, reason: "unknown block"}
      def decode(_other), do: %Fallback{type: nil, reason: "not a block"}

      defp decode_model(name, props) when is_map(props) do
        {module, fields} = Map.fetch!(@fields, name)

        Enum.reduce_while(fields, {:ok, struct(module)}, fn {field, type, required}, {:ok, acc} ->
          case {Map.get(props, Atom.to_string(field)), required} do
            {nil, true} -> {:halt, {:error, "\#{name}.\#{field} is missing"}}
            {nil, false} -> {:cont, {:ok, acc}}
            {value, _} ->
              case decode_value(type, value) do
                {:ok, value} -> {:cont, {:ok, Map.put(acc, field, value)}}
                :error -> {:halt, {:error, "\#{name}.\#{field} has the wrong type"}}
              end
          end
        end)
      end

      defp decode_model(name, _props), do: {:error, "\#{name} is not an object"}

      defp decode_value(:string, v) when is_binary(v), do: {:ok, v}
      defp decode_value(:integer, v) when is_integer(v), do: {:ok, v}
      defp decode_value(:boolean, v) when is_boolean(v), do: {:ok, v}

      defp decode_value({:list, type}, values) when is_list(values) do
        Enum.reduce_while(Enum.reverse(values), {:ok, []}, fn value, {:ok, acc} ->
          case decode_value(type, value) do
            {:ok, value} -> {:cont, {:ok, [value | acc]}}
            :error -> {:halt, :error}
          end
        end)
      end

      defp decode_value(model, value) when is_binary(model) do
        case decode_model(model, value) do
          {:ok, struct} -> {:ok, struct}
          {:error, _} -> :error
        end
      end

      defp decode_value(_type, _value), do: :error
    end
    """
    |> format()
  end

  defp client_table(spec) do
    models = Enum.map(spec.models ++ spec.blocks, & &1.name)

    Map.new(spec.models ++ spec.blocks, fn entry ->
      {Atom.to_string(entry.name),
       {Module.concat([module(entry.name)]),
        Enum.map(entry.fields, &{&1.name, client_type(&1.type, models), &1.required})}}
    end)
  end

  defp client_type({:list, inner}, models), do: {:list, client_type(inner, models)}
  defp client_type(type, models), do: if(type in models, do: Atom.to_string(type), else: type)

  defp module(name), do: "AtlasTui.Blocks." <> Macro.camelize(Atom.to_string(name))

  # JSON

  defp json(spec) do
    entry = fn e ->
      %{
        "name" => Atom.to_string(e.name),
        "fields" =>
          Enum.map(e.fields, fn f ->
            %{
              "name" => Atom.to_string(f.name),
              "type" => json_type(f.type),
              "required" => f.required
            }
          end)
      }
    end

    %{
      "version" => spec.version,
      "wire" =>
        ~s({"type": "<block>", "props": {...}}; an optional prop without a value is left out),
      "models" => Enum.map(spec.models, entry),
      "blocks" => Enum.map(spec.blocks, entry)
    }
    |> pretty()
  end

  defp json_type({:list, inner}), do: "list of " <> json_type(inner)
  defp json_type(type), do: Atom.to_string(type)

  # JSON with sorted keys and two-space indentation, so diffs stay small.
  defp pretty(value), do: IO.iodata_to_binary(pretty(value, 0)) <> "\n"

  defp pretty(map, level) when is_map(map) do
    inner =
      map
      |> Enum.sort()
      |> Enum.map(fn {k, v} ->
        [indent(level + 1), JSON.encode!(k), ": ", pretty(v, level + 1)]
      end)
      |> Enum.intersperse(",\n")

    ["{\n", inner, "\n", indent(level), "}"]
  end

  defp pretty([], _level), do: "[]"

  defp pretty(list, level) when is_list(list) do
    inner =
      list |> Enum.map(&[indent(level + 1), pretty(&1, level + 1)]) |> Enum.intersperse(",\n")

    ["[\n", inner, "\n", indent(level), "]"]
  end

  defp pretty(value, _level), do: JSON.encode!(value)

  defp indent(level), do: String.duplicate("  ", level)

  defp format(code), do: IO.iodata_to_binary([Code.format_string!(code), "\n"])
end
