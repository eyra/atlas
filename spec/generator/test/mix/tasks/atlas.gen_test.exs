defmodule Mix.Tasks.Atlas.GenTest do
  # Sets the application's config, so not async.
  use ExUnit.Case

  @moduletag :tmp_dir

  setup %{tmp_dir: dir} do
    Application.put_env(:atlas_spec, :contract, AtlasSpec.Example)
    Application.put_env(:atlas_spec, :targets, json: dir)
    Mix.shell(Mix.Shell.Process)

    on_exit(fn ->
      for key <- [:contract, :targets], do: Application.delete_env(:atlas_spec, key)
      Mix.shell(Mix.Shell.IO)
    end)

    %{json: Path.join(dir, "blocks.json")}
  end

  defp gen(args \\ []), do: Mix.Tasks.Atlas.Gen.run(args)

  test "writes each file with its header; --check passes after", %{json: json} do
    gen()

    assert "{\n  \"$comment\": \"Generated by atlas (mix atlas.gen). Do not edit: change " <> _ =
             File.read!(json)

    assert File.read!(json) =~ "test/support/example.ex and regenerate."
    gen(["--check"])
    assert_received {:mix_shell, :info, ["generated files are up to date"]}
  end

  test "--check fails on a stale file and writes nothing", %{json: json} do
    gen()
    File.write!(json, String.replace(File.read!(json), "card", "kard"))
    assert_raise Mix.Error, ~r/out of date.*blocks.json/, fn -> gen(["--check"]) end
    assert File.read!(json) =~ "kard"
  end

  test "a file with the header that no target writes is left over", %{tmp_dir: dir} do
    gen()
    old = Path.join(dir, "old.json")
    File.write!(old, File.read!(Path.join(dir, "blocks.json")))
    assert_raise Mix.Error, ~r/old.json \(left over\)/, fn -> gen(["--check"]) end
    gen()
    refute File.exists?(old)
  end

  test "a hand-written file is never overwritten nor removed", %{tmp_dir: dir, json: json} do
    File.write!(json, "{\n  \"mine\": true\n}\n")
    readme = Path.join(dir, "notes.json")
    File.write!(readme, "{\n  \"note\": \"Generated by atlas, they say\"\n}\n")
    assert_raise Mix.Error, ~r/no generated header; it is not overwritten/, fn -> gen() end
    assert File.read!(json) =~ "mine"
    File.rm!(json)
    gen()
    assert File.exists?(readme)
  end

  test "an unknown target fails before anything is written", %{tmp_dir: dir} do
    Application.put_env(:atlas_spec, :targets, swift: dir)
    assert_raise Mix.Error, ~r/unknown target :swift; known: \[:json\]/, fn -> gen() end
    assert File.ls!(dir) == []
  end

  test "the targets read only a contract's data, not the schema's internals" do
    for path <- Path.wildcard("lib/**/*.ex") -- ["lib/atlas_spec/schema.ex"] do
      code = path |> File.read!() |> String.replace(~r/@(module)?doc\s+"""(?s:.*?)"""/, "")
      refute code =~ "AtlasSpec.Schema.", "#{path} calls into AtlasSpec.Schema"
    end
  end
end
